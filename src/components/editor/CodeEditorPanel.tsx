import React, { useState, useEffect } from 'react';
import { PortfolioSchema } from '../../types/portfolio';
import { Copy, Check, RefreshCw, AlertCircle, Sparkles, FileCode, Braces, Code } from 'lucide-react';

interface CodeEditorPanelProps {
  schema: PortfolioSchema;
  onApplySchema: (updatedSchema: PortfolioSchema) => void;
  onResetSchema: () => void;
  isCompact?: boolean;
}

export const CodeEditorPanel: React.FC<CodeEditorPanelProps> = ({
  schema,
  onApplySchema,
  onResetSchema,
  isCompact = false
}) => {
  const [editorMode, setEditorMode] = useState<'json' | 'jsx' | 'craft'>('json');
  const [jsonText, setJsonText] = useState('');
  const [error, setError] = useState<string | null>(null);
  const [copied, setCopied] = useState(false);
  const [hasUnsavedChanges, setHasUnsavedChanges] = useState(false);

  // Sync state whenever schema prop updates from visual canvas
  useEffect(() => {
    if (!hasUnsavedChanges) {
      setJsonText(JSON.stringify(schema, null, 2));
      setError(null);
    }
  }, [schema, hasUnsavedChanges]);

  // Handle direct text changes in the JSON code editor
  const handleTextChange = (e: React.ChangeEvent<HTMLTextAreaElement>) => {
    const val = e.target.value;
    setJsonText(val);
    setHasUnsavedChanges(true);

    try {
      const parsed = JSON.parse(val);
      if (parsed && parsed.sections && Array.isArray(parsed.sections)) {
        setError(null);
      } else {
        setError('JSON structure must include "sections" array as per document specification.');
      }
    } catch (err: any) {
      setError(err.message || 'Invalid JSON syntax');
    }
  };

  const handleApply = () => {
    try {
      const parsed = JSON.parse(jsonText);
      if (!parsed.sections || !Array.isArray(parsed.sections)) {
        setError('Cannot apply: Schema must contain "sections" array.');
        return;
      }
      onApplySchema(parsed);
      setHasUnsavedChanges(false);
      setError(null);
    } catch (err: any) {
      setError(`Cannot apply: ${err.message}`);
    }
  };

  const handleFormat = () => {
    try {
      const parsed = JSON.parse(jsonText);
      setJsonText(JSON.stringify(parsed, null, 2));
      setError(null);
    } catch (err: any) {
      setError(`Cannot format: ${err.message}`);
    }
  };

  const handleCopy = () => {
    const textToCopy = editorMode === 'jsx' ? generateJsxCode(schema) : jsonText;
    navigator.clipboard.writeText(textToCopy);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  // Generate clean React + Tailwind component output
  const generateJsxCode = (currentSchema: PortfolioSchema): string => {
    return `// Generated by FolioCraft Visual Builder
// Framework: React 18+ / Next.js with Tailwind CSS
import React from 'react';

export default function PortfolioPage() {
  return (
    <main className="min-h-screen bg-slate-950 text-slate-100 font-sans">
${currentSchema.sections
  .map((sec) => `      {/* ${sec.type} Section */}
      <section className="px-6 md:px-12 ${sec.paddingY || 'py-20'} bg-[${sec.backgroundColor || '#090d16'}]">
        <div className="max-w-4xl mx-auto">
          <h2 className="text-3xl font-bold tracking-tight text-white mb-2">
            ${sec.components.title?.text || ''}
          </h2>
          <p className="text-slate-400 text-lg mb-6">
            ${sec.components.subtitle?.text || ''}
          </p>
          ${sec.components.ctaButton ? `<a href="${sec.components.ctaButton.link}" className="inline-block px-6 py-3 rounded-lg font-semibold bg-[${sec.components.ctaButton.styles?.backgroundColor || currentSchema.accentColor}] text-slate-950">
            ${sec.components.ctaButton.label}
          </a>` : ''}
        </div>
      </section>`)
  .join('\n\n')}
    </main>
  );
}`;
  };

  // Generate Craft.js serialized node representation
  const generateCraftSerialized = (currentSchema: PortfolioSchema) => {
    const craftNodes: Record<string, any> = {
      ROOT: {
        type: { resolvedName: 'CanvasContainer' },
        isCanvas: true,
        props: { className: 'min-h-screen' },
        displayName: 'RootCanvas',
        custom: {},
        parent: null,
        nodes: currentSchema.sections.map(s => s.id),
        linkedNodes: {}
      }
    };

    currentSchema.sections.forEach((s, idx) => {
      craftNodes[s.id] = {
        type: { resolvedName: `${s.type}Section` },
        isCanvas: false,
        props: {
          id: s.id,
          type: s.type,
          backgroundColor: s.backgroundColor,
          components: s.components
        },
        displayName: `${s.type} Node`,
        parent: 'ROOT',
        nodes: [],
        linkedNodes: {}
      };
    });

    return JSON.stringify(craftNodes, null, 2);
  };

  const lineCount = jsonText.split('\n').length;

  return (
    <div className="flex flex-col h-full bg-[#0d1117] text-slate-200 select-text overflow-hidden font-mono text-xs">
      {/* Top Editor Bar */}
      <div className="flex flex-wrap items-center justify-between gap-3 px-4 py-2.5 bg-[#161b22] border-b border-slate-800 shrink-0">
        <div className="flex items-center gap-2">
          {/* Mode Switcher */}
          <div className="flex items-center p-0.5 bg-slate-900 rounded-lg border border-slate-700/60 font-sans">
            <button
              onClick={() => setEditorMode('json')}
              className={`px-2.5 py-1 rounded text-xs flex items-center gap-1.5 transition-colors cursor-pointer ${
                editorMode === 'json' ? 'bg-indigo-600 text-white font-medium shadow-sm' : 'text-slate-400 hover:text-white'
              }`}
            >
              <Braces className="w-3.5 h-3.5" />
              <span>JSON Schema</span>
            </button>
            <button
              onClick={() => setEditorMode('jsx')}
              className={`px-2.5 py-1 rounded text-xs flex items-center gap-1.5 transition-colors cursor-pointer ${
                editorMode === 'jsx' ? 'bg-indigo-600 text-white font-medium shadow-sm' : 'text-slate-400 hover:text-white'
              }`}
            >
              <Code className="w-3.5 h-3.5" />
              <span>React JSX</span>
            </button>
            <button
              onClick={() => setEditorMode('craft')}
              className={`px-2.5 py-1 rounded text-xs flex items-center gap-1.5 transition-colors cursor-pointer ${
                editorMode === 'craft' ? 'bg-indigo-600 text-white font-medium shadow-sm' : 'text-slate-400 hover:text-white'
              }`}
            >
              <FileCode className="w-3.5 h-3.5" />
              <span>Craft.js Nodes</span>
            </button>
          </div>

          {hasUnsavedChanges && editorMode === 'json' && (
            <span className="text-[11px] font-sans text-amber-400 bg-amber-400/10 px-2 py-0.5 rounded border border-amber-400/20">
              Unsaved edits
            </span>
          )}
        </div>

        {/* Action Buttons */}
        <div className="flex items-center gap-2 font-sans">
          {editorMode === 'json' && (
            <>
              <button
                onClick={handleFormat}
                className="px-2.5 py-1 text-xs bg-slate-800 hover:bg-slate-700 text-slate-300 rounded border border-slate-700 transition-colors cursor-pointer"
              >
                Format
              </button>
              <button
                disabled={!hasUnsavedChanges || !!error}
                onClick={handleApply}
                className="px-3 py-1 text-xs bg-emerald-600 hover:bg-emerald-500 disabled:opacity-40 disabled:cursor-not-allowed text-white rounded font-medium transition-colors shadow-sm cursor-pointer"
              >
                Apply to Canvas
              </button>
            </>
          )}

          <button
            onClick={handleCopy}
            className="flex items-center gap-1.5 px-2.5 py-1 text-xs bg-slate-800 hover:bg-slate-700 text-slate-300 rounded border border-slate-700 transition-colors cursor-pointer"
          >
            {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
            <span>{copied ? 'Copied!' : 'Copy'}</span>
          </button>

          <button
            onClick={onResetSchema}
            title="Reset to Theme Defaults"
            className="p-1 text-slate-400 hover:text-white transition-colors cursor-pointer"
          >
            <RefreshCw className="w-3.5 h-3.5" />
          </button>
        </div>
      </div>

      {/* Error Banner */}
      {error && editorMode === 'json' && (
        <div className="px-4 py-2 bg-rose-500/15 border-b border-rose-500/30 text-rose-300 flex items-center gap-2 text-xs font-sans">
          <AlertCircle className="w-4 h-4 shrink-0 text-rose-400" />
          <span className="truncate">{error}</span>
        </div>
      )}

      {/* Editor Body with Line Numbers */}
      <div className="flex-1 relative flex overflow-hidden">
        {editorMode === 'json' ? (
          <div className="flex-1 flex h-full">
            {/* Line numbers gutter */}
            <div className="w-12 py-3 bg-[#11161d] text-slate-600 text-right pr-3 select-none overflow-hidden font-mono text-[11px] leading-5">
              {Array.from({ length: Math.min(lineCount, 600) }).map((_, i) => (
                <div key={i}>{i + 1}</div>
              ))}
            </div>

            {/* Editable JSON textarea */}
            <textarea
              value={jsonText}
              onChange={handleTextChange}
              spellCheck={false}
              className="flex-1 p-3 bg-transparent text-emerald-400 font-mono text-[11px] leading-5 resize-none focus:outline-none focus:ring-0 overflow-auto border-0"
            />
          </div>
        ) : editorMode === 'jsx' ? (
          <pre className="flex-1 p-4 overflow-auto text-indigo-300 text-[11px] leading-relaxed font-mono">
            <code>{generateJsxCode(schema)}</code>
          </pre>
        ) : (
          <pre className="flex-1 p-4 overflow-auto text-amber-300 text-[11px] leading-relaxed font-mono">
            <code>{generateCraftSerialized(schema)}</code>
          </pre>
        )}
      </div>

      {/* Status Bar */}
      <div className="px-4 py-1.5 bg-[#161b22] border-t border-slate-800 text-[11px] text-slate-500 flex items-center justify-between font-sans">
        <div className="flex items-center gap-3">
          <span>UTF-8</span>
          <span>·</span>
          <span>{editorMode === 'json' ? 'JSON (Schema Doc §3)' : editorMode === 'jsx' ? 'React JSX' : 'Craft.js Node Tree'}</span>
        </div>
        <div className="flex items-center gap-2">
          <span className="w-2 h-2 rounded-full bg-emerald-500 inline-block"></span>
          <span className="text-slate-400">Two-way AST synchronization</span>
        </div>
      </div>
    </div>
  );
};
